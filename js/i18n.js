var validLangs = ['pt-BR', 'en-US', 'es-ES', 'it-IT'];
var langUrlMap = {
  'pt': 'pt-BR',
  'pt-BR': 'pt-BR',
  'en': 'en-US',
  'en-US': 'en-US',
  'es': 'es-ES',
  'es-ES': 'es-ES',
  'it': 'it-IT',
  'it-IT': 'it-IT'
};
var langCodeMap = { 'pt-BR': 'pt', 'en-US': 'en', 'es-ES': 'es', 'it-IT': 'it' };

function normalizeLang(lang) {
  return langUrlMap[lang] || null;
}

function getLangFromUrl() {
  var params = new URLSearchParams(window.location.search);
  return normalizeLang(params.get('lang'));
}

function getCurrentLanguage() {
  var urlLang = getLangFromUrl();
  if (urlLang) return urlLang;

  var saved;
  try { saved = localStorage.getItem('gide-lang'); } catch(e) {}
  return normalizeLang(saved) || 'pt-BR';
}

function updateCurrentUrlLang(lang, replace) {
  var url = new URL(window.location.href);
  url.searchParams.set('lang', langCodeMap[lang] || 'pt');

  if (url.href === window.location.href) return;
  var method = replace ? 'replaceState' : 'pushState';
  window.history[method]({}, '', url);
}

function isLocalSiteLink(url) {
  return url.origin === window.location.origin &&
    !/\.(?:css|js|png|jpe?g|gif|webp|svg|mp4|pdf|zip)$/i.test(url.pathname);
}

function formatLocalizedHref(url) {
  if (url.protocol === 'file:') return url.href;
  return url.pathname + url.search + url.hash;
}

function localizeInternalLinks(lang) {
  document.querySelectorAll('a[href]').forEach(function(link) {
    var href = link.getAttribute('href');
    if (!href || href.charAt(0) === '?' || /^(?:https?:)?\/\/|mailto:|tel:|sms:|whatsapp:/i.test(href)) return;

    var url;
    try {
      url = new URL(href, window.location.href);
    } catch(e) {
      return;
    }

    if (!isLocalSiteLink(url)) return;
    url.searchParams.set('lang', langCodeMap[lang] || 'pt');
    link.setAttribute('href', formatLocalizedHref(url));
  });
}

function applyLanguage(lang) {
  lang = normalizeLang(lang) || 'pt-BR';
  var t = translations[lang];
  if (!t) return;

  // textContent updates
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (el.dataset.i18nOriginalText === undefined) {
      el.dataset.i18nOriginalText = el.textContent;
    }
    if (t[key] !== undefined) {
      el.textContent = t[key];
    } else {
      el.textContent = el.dataset.i18nOriginalText;
    }
  });

  // innerHTML updates (for content with <br> or inline SVG)
  document.querySelectorAll('[data-i18n-html]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-html');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  // aria-label updates
  document.querySelectorAll('[data-i18n-aria]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-aria');
    if (t[key] !== undefined) el.setAttribute('aria-label', t[key]);
  });

  // placeholder updates
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) el.setAttribute('placeholder', t[key]);
  });

  // <html lang>
  document.documentElement.lang = lang;

  // <title> — per-page via data-page on <body>, fallback to generic key
  var pageKey = document.body.getAttribute('data-page');
  var titleKey = pageKey ? 'page.' + pageKey + '.title' : 'page.title';
  if (t[titleKey]) document.title = t[titleKey];

  // Save preference
  try { localStorage.setItem('gide-lang', lang); } catch(e) {}

  // Update globe button code
  var currentCode = document.querySelector('.lang-current-code');
  var codeMap = { 'pt-BR': 'PT', 'en-US': 'EN', 'es-ES': 'ES', 'it-IT': 'IT' };
  if (currentCode) currentCode.textContent = codeMap[lang] || 'PT';

  // Update aria-selected on dropdown options
  document.querySelectorAll('.lang-option').forEach(function(opt) {
    var selected = opt.getAttribute('data-lang') === lang;
    opt.setAttribute('aria-selected', String(selected));
  });

  localizeInternalLinks(lang);
}

document.addEventListener('DOMContentLoaded', function() {
  var saved;
  try { saved = localStorage.getItem('gide-lang'); } catch(e) {}
  var urlLang = getLangFromUrl();
  var lang = urlLang || (validLangs.indexOf(saved) !== -1 ? saved : 'pt-BR');
  updateCurrentUrlLang(lang, true);

  // Dropdown open/close
  var globeBtn = document.querySelector('.lang-globe-btn');
  var dropdown = document.querySelector('.lang-dropdown');

  if (globeBtn && dropdown) {
    globeBtn.addEventListener('click', function(e) {
      e.stopPropagation();
      var isOpen = dropdown.classList.contains('open');
      dropdown.classList.toggle('open', !isOpen);
      globeBtn.setAttribute('aria-expanded', String(!isOpen));
    });

    document.addEventListener('click', function() {
      dropdown.classList.remove('open');
      globeBtn.setAttribute('aria-expanded', 'false');
    });

    dropdown.querySelectorAll('.lang-option').forEach(function(opt) {
      opt.addEventListener('click', function(e) {
        e.stopPropagation();
        var selectedLang = normalizeLang(opt.getAttribute('data-lang')) || 'pt-BR';
        updateCurrentUrlLang(selectedLang, false);
        applyLanguage(selectedLang);
        dropdown.classList.remove('open');
        globeBtn.setAttribute('aria-expanded', 'false');
      });
    });
  }

  applyLanguage(lang);
});
